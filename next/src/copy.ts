export const LANGS: Lang[] = ['en', 'pt', 'ru', 'zh-cn', 'zh-tw'];

/** What each language calls itself, which is the only name worth putting in
 *  a picker: a reader who needs the Russian one is not looking for the word
 *  "Russian" written in English. */
export const LANG_NAMES: Record<Lang, string> = {
  en: 'English',
  pt: 'Português',
  ru: 'Русский',
  'zh-cn': '简体中文',
  'zh-tw': '繁體中文',
};

/** What Intl should format numbers and dates in. Not the same string as the
 *  language code: the site writes `pt`, the platform wants `pt-BR`. */
export const LOCALES: Record<Lang, string> = {
  en: 'en-US',
  pt: 'pt-BR',
  ru: 'ru-RU',
  'zh-cn': 'zh-CN',
  'zh-tw': 'zh-TW',
};

export function pickLang(): Lang {
  /* No storage and no navigator on the build machine: the prerender says
     which language this file is, and it is the only answer there is. */
  if (typeof window === 'undefined') return 'en';
  const saved = localStorage.getItem('sp-lang') as Lang | null;
  if (saved && LANGS.includes(saved)) return saved;
  /* The same guess the server makes from Accept-Language, in the same order,
     so a reader who has never chosen gets the same language from the file
     nginx picks and from the script once it runs. */
  for (const raw of navigator.languages ?? [navigator.language ?? '']) {
    const tag = raw.toLowerCase();
    if (tag.startsWith('pt')) return 'pt';
    if (tag.startsWith('ru')) return 'ru';
    if (/^zh-(tw|hk|mo|hant)/.test(tag)) return 'zh-tw';
    if (tag.startsWith('zh')) return 'zh-cn';
    if (tag.startsWith('en')) return 'en';
  }
  return 'en';
}

/** `{name}` placeholders are filled from `vars`; a missing key is the key
 *  itself, which is the failure mode that gets noticed. */
export function translator(lang: Lang) {
  return (key: string, vars?: Record<string, string | number>) => {
    let s = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
    return s;
  };
}

export type T = ReturnType<typeof translator>;
